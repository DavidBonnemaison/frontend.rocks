import fs from 'node:fs';
import path from 'node:path';
import { clampChroma, formatHex, parse } from 'culori';
import { parseCliArgs } from '../../src/lib/cli-args';
import { SITE_ROOT } from '../../src/lib/paths';
import {
  COLOR_KEYS,
  PIECE_KEYS,
  parseTokensFile,
  type ColorKey,
  type PieceKey,
  type TokensFile,
} from './tokens-schema';

export const LAYER_ORDER_LINE =
  '@layer reset, tokens, base, legacy, layout, components, utilities;';

export function oklchToSrgbHex(oklchStr: string): string {
  const parsed = parse(oklchStr);
  if (!parsed) {
    throw new Error(`Unable to parse color "${oklchStr}"`);
  }
  const clamped = clampChroma(parsed, 'oklch');
  const hex = formatHex(clamped);
  if (!hex) {
    throw new Error(`Unable to format color "${oklchStr}" as hex`);
  }
  return hex;
}

export function generateTokensCss(tokens: TokensFile): string {
  const lines: string[] = [
    '/* GENERATED by scripts/design/build-tokens.ts from design/tokens.json. Do not edit. */',
    LAYER_ORDER_LINE,
    '',
    '@layer tokens {',
    '  :root {',
  ];

  for (const key of COLOR_KEYS) {
    lines.push(`    --color-${key}: ${tokens.color[key].light};`);
  }

  lines.push(`    --fixed-ink: ${tokens.fixed.ink};`);
  lines.push(`    --fixed-paper: ${tokens.fixed.paper};`);

  for (const key of PIECE_KEYS) {
    const entry = tokens.piece[key];
    lines.push(`    --piece-${key}: ${entry.fill};`);
    lines.push(`    --piece-${key}-on: var(--fixed-${entry.on});`);
  }

  if (tokens.font.display) {
    lines.push(
      `    --font-display: '${tokens.font.display.family}', ${tokens.font.display.fallback};`
    );
  } else {
    lines.push('    --font-display: var(--font-text);');
  }

  lines.push(`    --schematic-stroke: ${tokens.schematic.stroke}px;`);
  lines.push(`    --schematic-stroke-fine: ${tokens.schematic.strokeFine}px;`);
  lines.push(`    --schematic-label-size: ${tokens.schematic.labelSize}px;`);
  lines.push('  }');
  lines.push('');

  const lightDarkDecl = COLOR_KEYS.map(
    (key) => `      --color-${key}: light-dark(${tokens.color[key].light}, ${tokens.color[key].dark});`
  );

  lines.push('  @supports (color: light-dark(white, black)) {');
  lines.push('    :root {');
  lines.push(...lightDarkDecl);
  lines.push('    }');
  lines.push('  }');
  lines.push('');

  lines.push('  [data-theme="dark"] {');
  for (const key of COLOR_KEYS) {
    lines.push(`    --color-${key}: ${tokens.color[key].dark};`);
  }
  lines.push('  }');
  lines.push('');

  lines.push('  [data-theme="light"] {');
  for (const key of COLOR_KEYS) {
    lines.push(`    --color-${key}: ${tokens.color[key].light};`);
  }
  lines.push('  }');
  lines.push('');

  lines.push('  @supports (color: light-dark(white, black)) {');
  lines.push('    [data-theme="dark"],');
  lines.push('    [data-theme="light"] {');
  lines.push(...lightDarkDecl);
  lines.push('    }');
  lines.push('  }');
  lines.push('');

  for (const key of PIECE_KEYS) {
    lines.push(
      `  [data-piece="${key}"] { --piece: var(--piece-${key}); --piece-on: var(--piece-${key}-on); }`
    );
  }

  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

export function generateTokensTs(tokens: TokensFile): string {
  const lightSrgb: Record<ColorKey, string> = {} as Record<ColorKey, string>;
  const darkSrgb: Record<ColorKey, string> = {} as Record<ColorKey, string>;
  for (const key of COLOR_KEYS) {
    lightSrgb[key] = oklchToSrgbHex(tokens.color[key].light);
    darkSrgb[key] = oklchToSrgbHex(tokens.color[key].dark);
  }

  const pieceSrgb: Record<PieceKey, string> = {} as Record<PieceKey, string>;
  for (const key of PIECE_KEYS) {
    pieceSrgb[key] = oklchToSrgbHex(tokens.piece[key].fill);
  }

  const srgbObj = {
    light: lightSrgb,
    dark: darkSrgb,
    fixed: {
      ink: oklchToSrgbHex(tokens.fixed.ink),
      paper: oklchToSrgbHex(tokens.fixed.paper),
    },
    piece: pieceSrgb,
  };

  const fontFamilies = {
    text: tokens.font.text.family,
    meta: tokens.font.meta.family,
    readout: tokens.font.readout.family,
    display: tokens.font.display ? tokens.font.display.family : null,
  };

  return [
    '// GENERATED by scripts/design/build-tokens.ts from design/tokens.json. Do not edit.',
    `export const COLOR_KEYS = ${JSON.stringify(COLOR_KEYS)} as const;`,
    `export const PIECE_KEYS = ${JSON.stringify(PIECE_KEYS)} as const;`,
    `export const SRGB = ${JSON.stringify(srgbObj, null, 2)} as const;`,
    `export const FONT_FAMILIES = ${JSON.stringify(fontFamilies, null, 2)} as const;`,
    `export const SCHEMATIC = ${JSON.stringify(tokens.schematic, null, 2)} as const;`,
    '',
  ].join('\n');
}

async function main(): Promise<void> {
  const args = parseCliArgs(process.argv.slice(2), { check: 'boolean' });
  const tokensPath = path.join(SITE_ROOT, 'design', 'tokens.json');
  const cssOutPath = path.join(SITE_ROOT, 'src', 'styles', 'tokens.css');
  const tsOutPath = path.join(SITE_ROOT, 'src', 'lib', 'design', 'tokens.generated.ts');

  const raw = JSON.parse(fs.readFileSync(tokensPath, 'utf-8')) as unknown;
  const tokens = parseTokensFile(raw);

  const cssContent = generateTokensCss(tokens);
  const tsContent = generateTokensTs(tokens);

  if (args.check) {
    const diffs: string[] = [];
    const existingCss = fs.existsSync(cssOutPath) ? fs.readFileSync(cssOutPath, 'utf-8') : null;
    const existingTs = fs.existsSync(tsOutPath) ? fs.readFileSync(tsOutPath, 'utf-8') : null;
    if (existingCss !== cssContent) {
      diffs.push('src/styles/tokens.css');
    }
    if (existingTs !== tsContent) {
      diffs.push('src/lib/design/tokens.generated.ts');
    }
    if (diffs.length > 0) {
      console.error(
        `Design tokens are out of sync (${diffs.join(', ')}). Run: npm run design:tokens`
      );
      process.exit(1);
    }
    console.log('Design tokens are up to date.');
    return;
  }

  fs.mkdirSync(path.dirname(cssOutPath), { recursive: true });
  fs.mkdirSync(path.dirname(tsOutPath), { recursive: true });
  fs.writeFileSync(cssOutPath, cssContent, 'utf-8');
  fs.writeFileSync(tsOutPath, tsContent, 'utf-8');
  console.log('Generated src/styles/tokens.css and src/lib/design/tokens.generated.ts');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  });
}
